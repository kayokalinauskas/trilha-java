-- Schema do exercício 09.01. Suas entidades precisam bater com ele (ddl-auto=validate).

CREATE TABLE aluno (
    id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome  VARCHAR(120) NOT NULL,
    email VARCHAR(254) NOT NULL UNIQUE
);

CREATE TABLE turma (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo     VARCHAR(20)  NOT NULL UNIQUE,
    disciplina VARCHAR(120) NOT NULL,
    vagas      INT          NOT NULL CHECK (vagas > 0)
);

-- A associação muitos-para-muitos tem dados próprios (status, data): vira uma ENTIDADE.
CREATE TABLE matricula (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    aluno_id        BIGINT      NOT NULL REFERENCES aluno (id),
    turma_id        BIGINT      NOT NULL REFERENCES turma (id),
    status          VARCHAR(10) NOT NULL CHECK (status IN ('ATIVA', 'CANCELADA')),
    matriculada_em  TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_matricula_aluno_turma UNIQUE (aluno_id, turma_id)
);

CREATE INDEX ix_matricula_turma ON matricula (turma_id);
