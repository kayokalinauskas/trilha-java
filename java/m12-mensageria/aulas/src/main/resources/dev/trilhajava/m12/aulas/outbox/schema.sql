-- Aula 12.04: o esquema roda igual no H2 (modo PostgreSQL, nos testes) e no PostgreSQL 18.

CREATE TABLE produto (
    sku     VARCHAR(30) PRIMARY KEY,
    estoque INT         NOT NULL CHECK (estoque >= 0)
);

CREATE TABLE pedido (
    id         UUID           PRIMARY KEY,
    cliente    VARCHAR(100)   NOT NULL,
    sku        VARCHAR(30)    NOT NULL REFERENCES produto (sku),
    quantidade INT            NOT NULL,
    total      NUMERIC(12, 2) NOT NULL,
    criado_em  TIMESTAMP WITH TIME ZONE NOT NULL
);

-- A outbox: uma linha por evento, gravada na MESMA transação do pedido.
CREATE TABLE evento_saida (
    posicao           BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE, -- ordem de gravação
    id                UUID         PRIMARY KEY,   -- vai no header: o consumidor deduplica por ele
    agregado_tipo     VARCHAR(50)  NOT NULL,      -- "pedido"
    agregado_id       VARCHAR(100) NOT NULL,      -- vira a CHAVE da mensagem no Kafka
    tipo              VARCHAR(100) NOT NULL,      -- "PedidoConfirmado"
    payload           TEXT         NOT NULL,      -- o JSON do evento
    criado_em         TIMESTAMP WITH TIME ZONE NOT NULL,
    publicado_em      TIMESTAMP WITH TIME ZONE,   -- NULL = pendente
    tentativas        INT          NOT NULL DEFAULT 0,
    proxima_tentativa TIMESTAMP WITH TIME ZONE NOT NULL,
    ultimo_erro       VARCHAR(500)
);

-- A inbox do consumidor: um registro por evento já processado.
CREATE TABLE evento_recebido (
    evento_id   UUID         NOT NULL,
    consumidor  VARCHAR(100) NOT NULL,
    recebido_em TIMESTAMP WITH TIME ZONE NOT NULL,
    PRIMARY KEY (evento_id, consumidor)
);

CREATE TABLE saldo_de_pontos (
    cliente VARCHAR(100) PRIMARY KEY,
    pontos  INT          NOT NULL
);
