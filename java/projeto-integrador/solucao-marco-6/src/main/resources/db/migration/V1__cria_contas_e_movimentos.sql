CREATE TABLE conta (
    id        UUID PRIMARY KEY,
    titular   VARCHAR(120)   NOT NULL,
    cpf       VARCHAR(11)    NOT NULL,
    tipo      VARCHAR(10)    NOT NULL CHECK (tipo IN ('CORRENTE', 'POUPANCA')),
    saldo     NUMERIC(15, 2) NOT NULL CHECK (saldo >= 0),     -- a última linha de defesa
    criada_em TIMESTAMP WITH TIME ZONE NOT NULL,
    versao    BIGINT         NOT NULL DEFAULT 0,
    CONSTRAINT uk_conta_cpf_tipo UNIQUE (cpf, tipo)
);

CREATE TABLE movimento (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conta_id   UUID           NOT NULL REFERENCES conta (id),
    tipo       VARCHAR(30)    NOT NULL,
    valor      NUMERIC(15, 2) NOT NULL CHECK (valor > 0),
    saldo_apos NUMERIC(15, 2) NOT NULL,
    data_hora  TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX ix_movimento_conta ON movimento (conta_id, id);
