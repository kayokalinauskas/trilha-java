package dev.trilhajava.m07;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;

import java.math.BigDecimal;
import java.sql.SQLException;
import java.util.List;
import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;

@DisplayName("Exercício 07.04 — Repositório JDBC com PreparedStatement e transação")
class RepositorioDeContasTest {

    private Banco banco;
    private RepositorioDeContas repo;

    @BeforeEach
    void criar() throws SQLException {
        banco = new Banco();
        banco.executar("""
                CREATE TABLE conta (
                    id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    titular VARCHAR(120) NOT NULL,
                    saldo   NUMERIC(12,2) NOT NULL CHECK (saldo >= 0)
                );
                CREATE TABLE movimento (
                    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    conta_id  BIGINT NOT NULL REFERENCES conta(id),
                    valor     NUMERIC(12,2) NOT NULL,
                    descricao VARCHAR(200) NOT NULL
                );
                """);
        repo = new RepositorioDeContas(banco.dataSource());
    }

    @AfterEach
    void fechar() throws SQLException {
        banco.close();
    }

    private static BigDecimal bd(String v) {
        return new BigDecimal(v);
    }

    @Test
    @DisplayName("abre conta, devolve o id gerado e consulta o saldo")
    void abrir() {
        long id = repo.abrir("Ana", bd("100.00"));
        assertThat(repo.saldo(id)).hasValueSatisfying(s -> assertThat(s).isEqualByComparingTo("100"));
        assertThat(repo.saldo(999)).isEmpty();
    }

    @Test
    @DisplayName("texto malicioso é gravado literalmente (sem SQL injection)")
    void injecao() throws SQLException {
        String malicioso = "Robert'); DROP TABLE conta; --";
        long id = repo.abrir(malicioso, bd("1"));
        assertThat(banco.consultar("SELECT titular FROM conta WHERE id = ?", id)).containsExactly(List.of(malicioso));
    }

    @Test
    @DisplayName("transferência atualiza os dois saldos e registra dois movimentos")
    void transferir() {
        long a = repo.abrir("Ana", bd("100.00"));
        long b = repo.abrir("Bruno", bd("10.00"));
        repo.transferir(a, b, bd("30.00"));
        assertThat(repo.saldo(a)).hasValueSatisfying(s -> assertThat(s).isEqualByComparingTo("70"));
        assertThat(repo.saldo(b)).hasValueSatisfying(s -> assertThat(s).isEqualByComparingTo("40"));
        assertThat(repo.movimentos(a)).extracting(Movimento::valor).usingElementComparator(BigDecimal::compareTo).containsExactly(bd("-30"));
        assertThat(repo.movimentos(b)).extracting(Movimento::descricao).containsExactly("Transferência recebida da conta " + a);
    }

    @Test
    @DisplayName("saldo insuficiente: nada muda")
    void insuficiente() {
        long a = repo.abrir("Ana", bd("20.00"));
        long b = repo.abrir("Bruno", bd("0.00"));
        assertThatThrownBy(() -> repo.transferir(a, b, bd("20.01"))).isInstanceOf(SaldoInsuficienteException.class);
        assertThat(repo.saldo(a)).hasValueSatisfying(s -> assertThat(s).isEqualByComparingTo("20"));
        assertThat(repo.movimentos(a)).isEmpty();
    }

    @Test
    @DisplayName("destino inexistente: rollback, o débito da origem é desfeito")
    void rollback() {
        long a = repo.abrir("Ana", bd("50.00"));
        assertThatThrownBy(() -> repo.transferir(a, 999, bd("10.00"))).isInstanceOf(ContaNaoEncontradaException.class);
        assertThat(repo.saldo(a)).hasValueSatisfying(s -> assertThat(s).isEqualByComparingTo("50"));
        assertThat(repo.movimentos(a)).isEmpty();
    }

    @Test
    @DisplayName("valor precisa ser positivo e contas diferentes")
    void validacoes() {
        long a = repo.abrir("Ana", bd("50.00"));
        long b = repo.abrir("Bruno", bd("0"));
        assertThatThrownBy(() -> repo.transferir(a, b, bd("0"))).isInstanceOf(IllegalArgumentException.class);
        assertThatThrownBy(() -> repo.transferir(a, a, bd("1"))).isInstanceOf(IllegalArgumentException.class);
    }
}
