-- Solução de referência do exercício 07.01 (PostgreSQL; também roda no H2 em modo PostgreSQL).

CREATE TABLE paciente (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cpf         CHAR(11)     NOT NULL UNIQUE CHECK (LENGTH(cpf) = 11),
    nome        VARCHAR(120) NOT NULL,
    nascimento  DATE         NOT NULL,
    email       VARCHAR(254) UNIQUE          -- opcional: UNIQUE permite vários NULL
);

CREATE TABLE medico (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    crm           VARCHAR(20)  NOT NULL UNIQUE,
    nome          VARCHAR(120) NOT NULL,
    especialidade VARCHAR(60)  NOT NULL
);

CREATE TABLE consulta (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    paciente_id  BIGINT        NOT NULL REFERENCES paciente (id),   -- padrão: ON DELETE NO ACTION (bloqueia)
    medico_id    BIGINT        NOT NULL REFERENCES medico (id),
    inicio       TIMESTAMP     NOT NULL,
    duracao_min  INT           NOT NULL CHECK (duracao_min BETWEEN 15 AND 120),
    status       VARCHAR(10)   NOT NULL DEFAULT 'AGENDADA'
                               CHECK (status IN ('AGENDADA', 'REALIZADA', 'CANCELADA')),
    valor        NUMERIC(10, 2) NOT NULL CHECK (valor >= 0),
    CONSTRAINT uk_consulta_medico_inicio UNIQUE (medico_id, inicio)
);

-- Índice para "consultas de um paciente" (FKs NÃO ganham índice automático no PostgreSQL).
CREATE INDEX ix_consulta_paciente ON consulta (paciente_id);
